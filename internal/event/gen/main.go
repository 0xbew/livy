// Command gen writes the Event struct from the ledger event schema.
//
//	go run ./gen SCHEMA OUTPUT   (run by `go generate` in internal/event)
//
// It fails on a property shape it does not know, so a new kind of field is a decision,
// never a silent guess.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"reflect"
	"sort"
	"strings"
)

type prop struct {
	Type                 any              `json:"type"`
	Items                *prop            `json:"items"`
	Properties           map[string]*prop `json:"properties"`
	Required             []string         `json:"required"`
	AdditionalProperties any              `json:"additionalProperties"`
}

type field struct {
	key, name, goType, decode, encode string
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen SCHEMA OUTPUT")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	var root prop
	if err := json.Unmarshal(src, &root); err != nil {
		fail(err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/event/gen from schema/ledger-event.schema.json. DO NOT EDIT.\n\n")
	b.WriteString("package event\n\nimport \"fmt\"\n\n")
	var extra bytes.Buffer
	fields := make([]field, 0, len(root.Properties))
	for _, key := range sortedKeys(root.Properties) {
		f, err := fieldFor(key, root.Properties[key], &extra)
		if err != nil {
			fail(fmt.Errorf("property %s: %w", key, err))
		}
		fields = append(fields, f)
	}
	b.WriteString("// Event is one ledger line. A nil field is absent from the line.\ntype Event struct {\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "\t%s %s // %s\n", f.name, f.goType, f.key)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "var required = %#v\n\n", root.Required)
	b.WriteString("func (e *Event) set(key string, v any) (err error) {\n\tswitch key {\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "\tcase %q:\n\t\t%s\n", f.key, f.decode)
	}
	b.WriteString("\tdefault:\n\t\treturn fmt.Errorf(\"not in the schema\")\n\t}\n\treturn err\n}\n\n")
	b.WriteString("func (e Event) fields() map[string]any {\n\tm := map[string]any{}\n")
	for _, f := range fields {
		b.WriteString("\t" + f.encode + "\n")
	}
	b.WriteString("\treturn m\n}\n\n")
	b.Write(extra.Bytes())
	out, err := format.Source(b.Bytes())
	if err != nil {
		fail(fmt.Errorf("generated code does not parse: %w", err))
	}
	if err := os.WriteFile(os.Args[2], out, 0o644); err != nil {
		fail(err)
	}
}

func fieldFor(key string, p *prop, extra *bytes.Buffer) (field, error) {
	f := field{key: key, name: goName(key)}
	ptr := func(goType, as, value string) field {
		f.goType = "*" + goType
		f.decode = fmt.Sprintf("e.%s, err = %s(v)", f.name, as)
		f.encode = fmt.Sprintf("if e.%s != nil { m[%q] = %s }", f.name, key, fmt.Sprintf(value, "*e."+f.name))
		return f
	}
	null := func(goType, as string) field {
		f.goType = "Nullable[" + goType + "]"
		f.decode = fmt.Sprintf("e.%s, err = nullable(v, %s)", f.name, as)
		f.encode = fmt.Sprintf("if e.%s.Set { m[%q] = e.%s.value() }", f.name, key, f.name)
		return f
	}
	switch {
	case reflect.DeepEqual(p.Type, "string"):
		return ptr("string", "asString", "%s"), nil
	case reflect.DeepEqual(p.Type, "integer"):
		return ptr("int64", "asInt", "%s"), nil
	case reflect.DeepEqual(p.Type, "boolean"):
		return ptr("bool", "asBool", "%s"), nil
	case reflect.DeepEqual(p.Type, "number"):
		return ptr("Number", "asNumber", "%s"), nil
	case reflect.DeepEqual(p.Type, []any{"string", "null"}):
		return null("string", "asString"), nil
	case reflect.DeepEqual(p.Type, []any{"number", "null"}):
		return null("Number", "asNumber"), nil
	case reflect.DeepEqual(p.Type, "array") && p.Items != nil && reflect.DeepEqual(p.Items.Type, "string"):
		return ptr("[]string", "asStrings", "stringsValue(%s)"), nil
	case reflect.DeepEqual(p.Type, "object") && p.Properties == nil && isNumberSchema(p.AdditionalProperties):
		return ptr("map[string]Number", "asNumberMap", "numberMapValue(%s)"), nil
	case reflect.DeepEqual(p.Type, "array") && p.Items != nil && reflect.DeepEqual(p.Items.Type, "object"):
		item := f.name + "Item"
		if err := writeItem(item, p.Items, extra); err != nil {
			return f, err
		}
		return ptr("[]"+item, "as"+item+"s", "encode"+item+"s(%s)"), nil
	}
	return f, fmt.Errorf("unsupported shape %v", p.Type)
}

// writeItem generates a struct for an array's object items whose properties are strings.
func writeItem(name string, p *prop, b *bytes.Buffer) error {
	if p.AdditionalProperties != false {
		return fmt.Errorf("%s: items must set additionalProperties false", name)
	}
	isReq := map[string]bool{}
	for _, r := range p.Required {
		isReq[r] = true
	}
	keys := sortedKeys(p.Properties)
	for _, k := range keys {
		if !reflect.DeepEqual(p.Properties[k].Type, "string") {
			return fmt.Errorf("%s.%s: only string item properties are supported", name, k)
		}
	}
	fmt.Fprintf(b, "// %s is one element of the array; an optional property is a pointer.\ntype %s struct {\n", name, name)
	for _, k := range keys {
		t := "*string"
		if isReq[k] {
			t = "string"
		}
		fmt.Fprintf(b, "\t%s %s // %s\n", goName(k), t, k)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "func as%ss(v any) (*[]%s, error) {\n", name, name)
	fmt.Fprintf(b, "\tlist, ok := v.([]any)\n\tif !ok {\n\t\treturn nil, fmt.Errorf(\"want an array, got %%s\", kind(v))\n\t}\n")
	fmt.Fprintf(b, "\tout := make([]%s, 0, len(list))\n\tfor i, x := range list {\n", name)
	b.WriteString("\t\tobj, ok := x.(map[string]any)\n\t\tif !ok {\n\t\t\treturn nil, fmt.Errorf(\"[%d]: want an object, got %s\", i, kind(x))\n\t\t}\n")
	fmt.Fprintf(b, "\t\tvar it %s\n\t\tfor k, y := range obj {\n\t\t\tswitch k {\n", name)
	for _, k := range keys {
		if isReq[k] {
			fmt.Fprintf(b, "\t\t\tcase %q:\n\t\t\t\ts, err := asString(y)\n\t\t\t\tif err != nil {\n\t\t\t\t\treturn nil, fmt.Errorf(\"[%%d].%s: %%w\", i, err)\n\t\t\t\t}\n\t\t\t\tit.%s = *s\n", k, k, goName(k))
		} else {
			fmt.Fprintf(b, "\t\t\tcase %q:\n\t\t\t\ts, err := asString(y)\n\t\t\t\tif err != nil {\n\t\t\t\t\treturn nil, fmt.Errorf(\"[%%d].%s: %%w\", i, err)\n\t\t\t\t}\n\t\t\t\tit.%s = s\n", k, k, goName(k))
		}
	}
	b.WriteString("\t\t\tdefault:\n\t\t\t\treturn nil, fmt.Errorf(\"[%d].%s: not in the schema\", i, k)\n\t\t\t}\n\t\t}\n")
	for _, k := range p.Required {
		fmt.Fprintf(b, "\t\tif _, ok := obj[%q]; !ok {\n\t\t\treturn nil, fmt.Errorf(\"[%%d]: required %s missing\", i)\n\t\t}\n", k, k)
	}
	b.WriteString("\t\tout = append(out, it)\n\t}\n\treturn &out, nil\n}\n\n")
	fmt.Fprintf(b, "func encode%ss(list []%s) []any {\n\tout := make([]any, len(list))\n\tfor i, it := range list {\n\t\tm := map[string]any{}\n", name, name)
	for _, k := range keys {
		if isReq[k] {
			fmt.Fprintf(b, "\t\tm[%q] = it.%s\n", k, goName(k))
		} else {
			fmt.Fprintf(b, "\t\tif it.%s != nil {\n\t\t\tm[%q] = *it.%s\n\t\t}\n", goName(k), k, goName(k))
		}
	}
	b.WriteString("\t\tout[i] = m\n\t}\n\treturn out\n}\n\n")
	return nil
}

func isNumberSchema(v any) bool {
	m, ok := v.(map[string]any)
	return ok && reflect.DeepEqual(m["type"], "number")
}

func goName(key string) string {
	var b strings.Builder
	for _, part := range strings.Split(key, "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

func sortedKeys(m map[string]*prop) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
