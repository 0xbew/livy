package install

import (
	"bytes"
	"crypto/sha256"
	_ "embed" // the plugin template
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/0xbew/livy/internal/hook"
)

// The Amp plugin: a fixed TypeScript file in Amp's user plugin folder that hands each event to
// `livy amp`. Install writes it only when Amp's config folder exists, and only over a file
// carrying our marker; a livy.ts of anyone else's is named and left alone.

//go:embed ampplugin.ts
var ampTemplate string

// AmpMarker is the plugin file's first line: what makes a livy.ts ours.
const AmpMarker = "// livy: generated by livy install; livy uninstall removes this file. Do not edit."

// AmpTemplateVersion changes whenever the template does, so doctor can say a file is out of date.
const AmpTemplateVersion = "4"

// AmpPlugin is the plugin file for this binary and data folder, byte for byte.
func AmpPlugin(bin, dataDir string) []byte {
	quote := func(s string) string {
		b, _ := json.Marshal(s) // a string always encodes
		return string(b)
	}
	return []byte(strings.NewReplacer("__LIVY_BIN__", quote(bin), "__LIVY_DATA__", quote(dataDir),
		"__LIVY_TEMPLATE__", quote(AmpTemplateVersion)).Replace(ampTemplate))
}

// AmpPluginPath is where install writes the plugin, and the folder whose presence means Amp is here.
func AmpPluginPath(home string) (plugin, ampDir string) {
	ampDir = filepath.Join(home, ".config", "amp")
	return filepath.Join(ampDir, "plugins", "livy.ts"), ampDir
}

func ampSum(b []byte) string {
	s := sha256.Sum256(b)
	return hex.EncodeToString(s[:])
}

// ampIsOurs says the file starts with our marker line.
func ampIsOurs(b []byte) bool { return bytes.HasPrefix(b, []byte(AmpMarker+"\n")) }

// amp is step 4b: the Amp plugin, when Amp is on this machine and --no-amp is not given.
func (r *installRun) amp() {
	path, ampDir := AmpPluginPath(r.p.home)
	if r.prev.AmpPlugin != "" {
		path = r.prev.AmpPlugin
	}
	if r.o.noAmp {
		r.removeAmp(path)
		return
	}
	if _, err := os.Stat(ampDir); err != nil {
		r.say("amp: not on this machine (%s), skipped", ampDir)
		return
	}
	want := AmpPlugin(r.p.bin, hook.DataDir())
	have, err := os.ReadFile(path)
	switch {
	case err != nil && !errors.Is(err, fs.ErrNotExist):
		r.fail("amp: %s unreadable (%v), left alone", path, err)
		return
	case err == nil && !ampIsOurs(have):
		r.say("amp: %s is not ours (no Livy marker); left alone, so Amp is not recorded", path)
		return
	case err == nil && bytes.Equal(have, want):
		r.say("amp: plugin already current at %s", path)
		r.ownAmp(path, want)
		return
	case r.o.dry:
		r.say("amp: would write the plugin to %s", path)
		return
	}
	if err := writeAmpPlugin(path, want); err != nil {
		r.fail("amp: could not write %s: %v", path, err)
		return
	}
	r.ownAmp(path, want)
	r.say("amp: wrote the plugin to %s; restart Amp to load it", path)
}

func (r *installRun) ownAmp(path string, body []byte) {
	r.st.AmpPlugin, r.st.AmpPluginSHA256 = path, ampSum(body)
}

// removeAmp takes out a plugin an earlier install wrote, for --no-amp.
func (r *installRun) removeAmp(path string) {
	msg, bad := removeAmpPlugin(path, r.prev.AmpPluginSHA256, AmpPlugin(r.p.bin, hook.DataDir()), r.o.dry)
	r.failed = r.failed || bad
	if msg == "" {
		msg = "skipped (--no-amp)"
	}
	r.say("amp: %s", msg)
	if !bad && !r.o.dry {
		r.st.AmpPlugin, r.st.AmpPluginSHA256 = "", ""
	}
}

// writeAmpPlugin writes the file atomically, readable by Amp (0644), in a folder Amp can list.
func writeAmpPlugin(path string, body []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("make the plugin folder: %w", err)
	}
	return writeFileAtomic(path, body, 0o644)
}

// removeAmpPlugin removes our plugin file: only with our marker, and only as install wrote it
// (sum, when recorded; else byte-equal to current, this build's plugin). An edited one is kept
// and named. msg is "" when there is nothing to do.
func removeAmpPlugin(path, sum string, current []byte, dry bool) (msg string, bad bool) {
	have, err := os.ReadFile(path)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return "", false
	case err != nil:
		return fmt.Sprintf("could not read %s (%v); the Amp plugin was NOT removed", path, err), true
	case !ampIsOurs(have):
		return "", false
	case sum != "" && ampSum(have) != sum:
		return fmt.Sprintf("kept %s: it was edited after install; remove it yourself", path), true
	case sum == "" && !bytes.Equal(have, current):
		return fmt.Sprintf("kept %s: no install record of it, and it differs from this build's plugin; remove it yourself", path), true
	case dry:
		return "would remove the Amp plugin " + path, false
	}
	if err := os.Remove(path); err != nil {
		return fmt.Sprintf("could not remove %s: %v", path, err), true
	}
	return "removed the Amp plugin " + path + "; restart Amp to unload it", false
}

// ampPlugin removes the Amp plugin at uninstall.
func (u *uninstallRun) ampPlugin() {
	path := u.st.AmpPlugin
	if path == "" {
		path, _ = AmpPluginPath(u.p.home)
	}
	if msg, bad := removeAmpPlugin(path, u.st.AmpPluginSHA256, AmpPlugin(u.p.bin, hook.DataDir()), u.o.dry); msg != "" {
		u.failed = u.failed || bad
		u.say("amp: %s", msg)
	}
}
